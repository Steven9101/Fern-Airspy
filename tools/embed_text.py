"""Writes a C++ source file that carries text files as C strings, for the
licences --notices prints.

    embed_text.py NAME FILE... [-- NAME FILE...] > notices.cpp

Each NAME becomes a `const char NAME[]` in namespace fern holding its
files, separated by blank lines. A FILE written as head:PATH contributes
only the comment block PATH starts with: the vendor libraries keep their
copyright lines there, and their BSD licence asks that a binary carry them.
"""
import sys


def literal(text):
    # Adjacent literals of one line each: some compilers limit the length of
    # a single one.
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    lines = escaped.split("\n")
    return ["    \"%s\\n\"" % line for line in lines[:-1]] + ["    \"%s\";" % lines[-1]]


def read(spec):
    if not spec.startswith("head:"):
        return open(spec, encoding="utf-8").read().rstrip() + "\n"
    path = spec[len("head:"):]
    text = open(path, encoding="utf-8").read().lstrip()
    end = text.find("*/")
    if not text.startswith("/*") or end < 0:
        sys.exit("embed_text.py: %s does not start with a comment block" % path)
    return "%s:\n\n%s\n" % (path, text[:end + 2])


def main():
    groups = [[]]
    for arg in sys.argv[1:]:
        if arg == "--":
            groups.append([])
        else:
            groups[-1].append(arg)
    if any(len(g) < 2 for g in groups):
        sys.exit("usage: embed_text.py NAME FILE... [-- NAME FILE...]")
    out = ["// Generated by tools/embed_text.py; do not edit.", "", "namespace fern {", ""]
    for name, *paths in groups:
        text = "\n\n".join(read(p) for p in paths)
        out.append("extern const char %s[];" % name)
        out.append("const char %s[] =" % name)
        out += literal(text)
        out.append("")
    out += ["}  // namespace fern", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
